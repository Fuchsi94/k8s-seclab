#!/usr/bin/env bash
# Installs containerd + kubeadm/kubelet/kubectl on Ubuntu and bootstraps the node:
#   ROLE=controlplane -> kubeadm init, join token, Cilium CNI, kubeconfig for the SSH user
#   ROLE=worker       -> waits for the API server, then kubeadm join
#
# Runs as root via GCP startup script on EVERY boot, so every step checks
# first whether it is already done.
#
# Templated by Terraform (templatefile): placeholders in dollar-brace form
# are filled in at apply time. Plain bash variables are therefore written
# as $VAR (without braces) so Terraform leaves them alone.
set -euo pipefail

ROLE="${ROLE}"
JOIN_TOKEN="${JOIN_TOKEN}"
CP_INTERNAL_IP="${CP_INTERNAL_IP}" # only used by the worker
SSH_USER="${SSH_USER}"
CILIUM_VERSION="${CILIUM_VERSION}"
CILIUM_CLI_VERSION="${CILIUM_CLI_VERSION}"

METADATA="http://metadata.google.internal/computeMetadata/v1/instance"
export HOME=/root # startup scripts run without HOME; cilium CLI (helm) needs it

# --- 1. Packages (skipped if kubeadm is already installed) ---
if ! command -v kubeadm >/dev/null 2>&1; then
  # Kernel prerequisites
  swapoff -a
  sed -i '/ swap / s/^/#/' /etc/fstab

  cat >/etc/modules-load.d/k8s.conf <<EOF
overlay
br_netfilter
EOF
  modprobe overlay
  modprobe br_netfilter

  cat >/etc/sysctl.d/k8s.conf <<EOF
net.bridge.bridge-nf-call-iptables  = 1
net.bridge.bridge-nf-call-ip6tables = 1
net.ipv4.ip_forward                 = 1
EOF
  sysctl --system

  # containerd (+ conntrack, required by kubeadm preflight / kube-proxy)
  apt-get update
  apt-get install -y containerd conntrack apt-transport-https ca-certificates curl gpg

  mkdir -p /etc/containerd
  containerd config default >/etc/containerd/config.toml
  sed -i 's/SystemdCgroup = false/SystemdCgroup = true/' /etc/containerd/config.toml
  systemctl restart containerd
  systemctl enable containerd

  # kubeadm/kubelet/kubectl from pkgs.k8s.io
  mkdir -p -m 755 /etc/apt/keyrings
  curl -fsSL "https://pkgs.k8s.io/core:/stable:/${K8S_VERSION}/deb/Release.key" \
    | gpg --dearmor --yes -o /etc/apt/keyrings/kubernetes-apt-keyring.gpg

  cat >/etc/apt/sources.list.d/kubernetes.list <<EOF
deb [signed-by=/etc/apt/keyrings/kubernetes-apt-keyring.gpg] https://pkgs.k8s.io/core:/stable:/${K8S_VERSION}/deb/ /
EOF

  apt-get update
  apt-get install -y kubelet kubeadm kubectl
  apt-mark hold kubelet kubeadm kubectl
  systemctl enable --now kubelet
fi

# --- 2a. Control plane: init (skipped if already initialized) ---
if [ "$ROLE" = "controlplane" ] && [ ! -f /etc/kubernetes/admin.conf ]; then
  INTERNAL_IP=$(curl -fs -H "Metadata-Flavor: Google" "$METADATA/network-interfaces/0/ip")
  PUBLIC_IP=$(curl -fs -H "Metadata-Flavor: Google" "$METADATA/network-interfaces/0/access-configs/0/external-ip")

  # The public IP goes into the API server cert (SAN) so kubectl works from
  # the laptop. The token is pre-generated by Terraform so the worker can join.
  kubeadm init \
    --token "$JOIN_TOKEN" \
    --pod-network-cidr=192.168.0.0/16 \
    --apiserver-advertise-address="$INTERNAL_IP" \
    --apiserver-cert-extra-sans="$PUBLIC_IP"
fi

if [ "$ROLE" = "controlplane" ]; then
  export KUBECONFIG=/etc/kubernetes/admin.conf

  # On reboot the API server needs a moment to come back. Wait for it,
  # otherwise the checks below would fail and set -e aborts the script.
  until kubectl get --raw /livez >/dev/null 2>&1; do
    echo "Waiting for local API server ..."
    sleep 5
  done

  # --- 2b. Join token (re-created if missing, e.g. expired after 24h) ---
  TOKEN_ID=$(echo "$JOIN_TOKEN" | cut -d. -f1)
  if ! kubeadm token list | grep -q "^$TOKEN_ID\."; then
    kubeadm token create "$JOIN_TOKEN"
  fi

  # --- 2c. Cilium CLI + CNI (skipped if already installed) ---
  if ! command -v cilium >/dev/null 2>&1; then
    CLI_TGZ=cilium-linux-amd64.tar.gz
    CLI_URL="https://github.com/cilium/cilium-cli/releases/download/$CILIUM_CLI_VERSION/$CLI_TGZ"
    cd /tmp
    curl -fsSLO "$CLI_URL"
    curl -fsSLO "$CLI_URL.sha256sum"
    sha256sum --check "$CLI_TGZ.sha256sum"
    tar -xzf "$CLI_TGZ" -C /usr/local/bin
    rm -f "$CLI_TGZ" "$CLI_TGZ.sha256sum"
    cd /
  fi

  if ! kubectl -n kube-system get daemonset cilium >/dev/null 2>&1; then
    # ipam.mode=kubernetes: use the per-node podCIDR from --pod-network-cidr
    #   (Cilium's default pool 10.0.0.0/8 would overlap the GCP VPC).
    # socketLB.hostNamespaceOnly: required for Kata Containers later.
    cilium install --version "$CILIUM_VERSION" \
      --set ipam.mode=kubernetes \
      --set socketLB.hostNamespaceOnly=true \
      --set hubble.relay.enabled=true
  fi
fi

# --- 2d. Control plane: kubeconfig for the SSH user (if missing) ---
if [ "$ROLE" = "controlplane" ] && [ ! -f "/home/$SSH_USER/.kube/config" ]; then
  # The guest agent creates the user from the ssh-keys metadata, possibly
  # after this script started. Wait up to 2 minutes for it.
  for _ in $(seq 1 60); do
    id "$SSH_USER" >/dev/null 2>&1 && break
    sleep 2
  done
  if id "$SSH_USER" >/dev/null 2>&1; then
    install -d -m 700 -o "$SSH_USER" -g "$(id -gn "$SSH_USER")" "/home/$SSH_USER/.kube"
    install -m 600 -o "$SSH_USER" -g "$(id -gn "$SSH_USER")" \
      /etc/kubernetes/admin.conf "/home/$SSH_USER/.kube/config"
  else
    echo "User $SSH_USER not found, skipping kubeconfig copy"
  fi
fi

# --- 3. Worker: join (skipped if already joined) ---
if [ "$ROLE" = "worker" ] && [ ! -f /etc/kubernetes/kubelet.conf ]; then
  # Wait until the API server on the control plane answers.
  until curl -fsk --max-time 5 "https://$CP_INTERNAL_IP:6443/livez" >/dev/null; do
    echo "Waiting for API server at $CP_INTERNAL_IP:6443 ..."
    sleep 10
  done

  # No CA pinning: acceptable inside the lab network, see README.
  kubeadm join "$CP_INTERNAL_IP:6443" \
    --token "$JOIN_TOKEN" \
    --discovery-token-unsafe-skip-ca-verification
fi

# Mark provisioning done so the user knows when to log in.
touch /var/lib/gcp-sec-lab-ready
